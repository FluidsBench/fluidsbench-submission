import hashlib
import http.client
import os
import re
import shutil
import stat
import tempfile
import time
import urllib.error
import urllib.request
import uuid
import zipfile
from functools import lru_cache
from pathlib import Path

from reference.hosting import support_url

from reference.scoring_support import load_support_release

from .contract import REPOSITORY_REVISION, read_json, sha256_file

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "benchmark-specs/ahmedml"
RELEASE_ID = "ahmedml-native-all-splits-support-v1-candidate"
RELEASE_SHA256 = "c727bad2ca2566dfed44920cc334af136f2fbe32f3c8886b2fcb130f495fd124"
CONTRACT_SHA256 = "9ddbd006f23130d2d581202635b3686b0689a0882d62cc3a7362bb9c192a325e"
RELEASE_TAG = "ahmedml-derived-cache-v1-dev"
BASE_URL = (
    "https://github.com/neilashton/fluidsbench-submission/releases/download/"
    + RELEASE_TAG
    + "/"
)
INDEX_PATH = SPEC / "support-distribution-v1.json"
SPLITS = (
    "full",
    "medium",
    "scarce",
    "super_scarce",
    "geometry",
    "high_drag",
    "low_drag",
    "image_wake",
)
CASE_SETS = (
    "full-test",
    "geometry-test",
    "high_drag-test",
    "low_drag-test",
    "image_wake-test",
)
BLOCK_BYTES = 4 * 1024 * 1024


class SupportDistributionError(ValueError):
    """The requested cache cannot be installed with its frozen identity."""


def select_cases(
    *, split: str | None = None, case_ids: list[str] | None = None
) -> list[str]:
    if split is not None and (split not in SPLITS or case_ids is not None):
        raise SupportDistributionError("choose one supported split or explicit cases")
    all_cases = []
    selected = []
    for name in SPLITS:
        cases = read_json(SPEC / "splits" / f"{name}.json", label="split")["case_ids"]
        all_cases.extend(c for c in cases if c not in all_cases)
        if name == split:
            selected = cases
    if case_ids is not None:
        if (
            not case_ids
            or len(set(case_ids)) != len(case_ids)
            or not set(case_ids) <= set(all_cases)
        ):
            raise SupportDistributionError(
                "case IDs must be unique members of the AhmedML test sets"
            )
        return list(case_ids)
    return selected if split is not None else all_cases


@lru_cache(maxsize=1)
def canonical_records() -> dict[str, tuple[Path, dict]]:
    """Resolve existing Git case manifests through the pinned release chain."""
    root = SPEC / "scoring-support" / RELEASE_ID
    manifest = root / "manifest.json"
    if (
        sha256_file(manifest) != RELEASE_SHA256
        or sha256_file(SPEC / "derived-cache-contract-v1.json") != CONTRACT_SHA256
    ):
        raise SupportDistributionError(
            "AhmedML scientific release or cache contract differs"
        )
    result = {}
    for case_set in CASE_SETS:
        release = load_support_release(manifest, case_set)
        for case_id, case in release.cases.items():
            digests = {x["expected_support_sha256"] for x in case["support_instances"]}
            path = (
                root
                / "case-sets"
                / case_set
                / "case-artifacts"
                / case_id
                / "case-support.json"
            )
            if digests != {sha256_file(path)}:
                raise SupportDistributionError(
                    f"{case_id}: canonical support manifest differs"
                )
            document = read_json(path, label="canonical case support")
            if case_id in result and result[case_id][1] != document:
                raise SupportDistributionError(
                    f"{case_id}: inconsistent case-set support"
                )
            result[case_id] = (path, document)
    if set(result) != set(select_cases()) or len(result) != 316:
        raise SupportDistributionError(
            "canonical support must cover all 316 test cases"
        )
    return result


def expected_files(case_id: str) -> dict[str, dict]:
    records = canonical_records()
    if case_id not in records:
        raise SupportDistributionError(f"unknown AhmedML support case: {case_id}")
    path, document = records[case_id]
    result = {
        "case-support.json": {
            "size_bytes": path.stat().st_size,
            "sha256": sha256_file(path),
        }
    }
    for artifact in document["artifacts"].values():
        name = artifact["path"]
        if Path(name).name != name or name in result or "\\" in name:
            raise SupportDistributionError("invalid canonical artifact basename")
        result[name] = {key: artifact[key] for key in ("size_bytes", "sha256")}
    if len(result) != 5:
        raise SupportDistributionError(
            "expected a case manifest and four support payloads"
        )
    return result


def load_distribution() -> dict:
    index = read_json(INDEX_PATH, label="AhmedML support distribution")
    header = {
        "schema": "fluidsbench-ahmedml-support-distribution-v1",
        "schema_version": 1,
        "status": "dev_prerelease",
        "dataset_revision": REPOSITORY_REVISION,
        "scientific_release_id": RELEASE_ID,
        "scientific_manifest_sha256": RELEASE_SHA256,
        "derived_cache_contract_sha256": CONTRACT_SHA256,
        "release_tag": RELEASE_TAG,
    }
    if any(index.get(k) != v for k, v in header.items()):
        raise SupportDistributionError(
            "support distribution scientific bindings differ"
        )
    cases = index.get("cases")
    if not isinstance(cases, dict) or set(cases) != set(canonical_records()):
        raise SupportDistributionError(
            "distribution must cover exactly the canonical test cases"
        )
    for case_id, entry in cases.items():
        files = expected_files(case_id)
        if (
            not isinstance(entry, dict)
            or entry.get("url") != BASE_URL + f"ahmedml-support-{case_id}.zip"
            or entry.get("case_manifest_sha256") != files["case-support.json"]["sha256"]
            or entry.get("expanded_bytes")
            != sum(f["size_bytes"] for f in files.values())
            or type(entry.get("size_bytes")) is not int
            or not 0 < entry["size_bytes"] < 2 * 1024**3
            or not isinstance(entry.get("sha256"), str)
            or re.fullmatch(r"[0-9a-f]{64}", entry["sha256"]) is None
        ):
            raise SupportDistributionError(
                f"{case_id}: invalid support transport binding"
            )
    return index


def cache_root(destination: Path | None = None) -> Path:
    if destination is not None:
        return destination.expanduser().resolve()
    configured = os.environ.get("FLUIDSBENCH_AHMEDML_SUPPORT_ROOT")
    if configured:
        return Path(configured).expanduser().resolve()
    base = Path(os.environ.get("XDG_CACHE_HOME", str(Path.home() / ".cache")))
    return (base.expanduser() / "fluidsbench/ahmedml" / RELEASE_SHA256).resolve()


def verify_case(directory: Path, files: dict[str, dict]) -> Path:
    if directory.is_symlink() or not directory.is_dir():
        raise SupportDistributionError(
            f"missing or unsafe support directory: {directory}"
        )
    if {p.name for p in directory.iterdir()} != set(files):
        raise SupportDistributionError(f"support inventory differs: {directory}")
    for name, identity in files.items():
        path = directory / name
        if (
            path.is_symlink()
            or not path.is_file()
            or path.stat().st_size != identity["size_bytes"]
            or sha256_file(path) != identity["sha256"]
        ):
            raise SupportDistributionError(f"support size or SHA-256 differs: {path}")
    return directory / "case-support.json"


class _HTTPSRedirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        if not newurl.startswith("https://"):
            raise SupportDistributionError("support download redirected outside HTTPS")
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def download_archive(entry: dict, target: Path) -> None:
    if not entry["url"].startswith("https://"):
        raise SupportDistributionError("support archive URL must use HTTPS")
    opener = urllib.request.build_opener(_HTTPSRedirects())
    for attempt in range(3):
        try:
            digest = hashlib.sha256()
            size = 0
            request = urllib.request.Request(
                support_url(entry["url"]), headers={"User-Agent": "FluidsBench-AhmedML-support/1"}
            )
            with opener.open(request, timeout=60) as response, target.open(
                "wb"
            ) as output:
                while block := response.read(BLOCK_BYTES):
                    size += len(block)
                    if size > entry["size_bytes"]:
                        raise SupportDistributionError(
                            "support archive exceeds its pinned size"
                        )
                    digest.update(block)
                    output.write(block)
            if size != entry["size_bytes"] or digest.hexdigest() != entry["sha256"]:
                raise SupportDistributionError(
                    "downloaded support archive size or SHA-256 differs"
                )
            return
        except (
            urllib.error.URLError,
            TimeoutError,
            ConnectionError,
            http.client.IncompleteRead,
        ) as error:
            if attempt == 2:
                raise SupportDistributionError(
                    f"support download failed after three attempts: {error}"
                ) from error
            time.sleep(attempt + 1)


def extract_archive(archive: Path, target: Path, files: dict[str, dict]) -> None:
    """Extract only the exact five known basenames, with bounded sizes."""
    with zipfile.ZipFile(archive) as bundle:
        entries = bundle.infolist()
        if len(entries) != len(files) or {x.filename for x in entries} != set(files):
            raise SupportDistributionError(
                "support archive contains missing, duplicate or unexpected files"
            )
        for item in entries:
            mode = item.external_attr >> 16
            if (
                item.is_dir()
                or stat.S_IFMT(mode) not in (0, stat.S_IFREG)
                or item.flag_bits & 1
                or item.file_size != files[item.filename]["size_bytes"]
            ):
                raise SupportDistributionError(
                    "support archive contains an unsafe member or wrong size"
                )
        target.mkdir()
        for item in entries:
            written = 0
            with bundle.open(item) as source, (target / item.filename).open(
                "xb"
            ) as output:
                while block := source.read(BLOCK_BYTES):
                    written += len(block)
                    if written > files[item.filename]["size_bytes"]:
                        raise SupportDistributionError(
                            "expanded support exceeds its pinned size"
                        )
                    output.write(block)
    verify_case(target, files)


def ensure_case_support(
    case_id: str,
    *,
    destination: Path | None = None,
    offline: bool = False,
    index: dict | None = None,
) -> Path:
    files = expected_files(case_id)
    root = cache_root(destination)
    directory = root / case_id
    # Offline checks perform no writes and never require transport metadata.
    if offline:
        return verify_case(directory, files)
    root.mkdir(parents=True, exist_ok=True)
    lock_flags = os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW
    with os.fdopen(
        os.open(root / f".{case_id}.lock", lock_flags, 0o600), "a+b"
    ) as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        try:
            return verify_case(directory, files)
        except SupportDistributionError:
            if directory.is_symlink() or (
                directory.exists() and not directory.is_dir()
            ):
                raise
        entry = (index or load_distribution())["cases"][case_id]
        required = entry["size_bytes"] + entry["expanded_bytes"]
        if shutil.disk_usage(root).free < required:
            raise SupportDistributionError(
                f"insufficient space for {case_id}: need {required} temporary bytes"
            )
        with tempfile.TemporaryDirectory(
            dir=root, prefix=f".{case_id}-install-"
        ) as temporary:
            staging = Path(temporary)
            archive = staging / "support.zip"
            download_archive(entry, archive)
            prepared = staging / case_id
            extract_archive(archive, prepared, files)
            backup = None
            if directory.exists():
                # Preserve a damaged existing cache rather than deleting user files.
                backup = root / f".{case_id}-replaced-{uuid.uuid4().hex}"
                directory.rename(backup)
            try:
                prepared.rename(directory)
            except BaseException:
                if backup is not None:
                    backup.rename(directory)
                raise
        return directory / "case-support.json"


def resolve_case_support(
    case_id: str,
    *,
    explicit: Path | None = None,
    destination: Path | None = None,
    offline: bool = False,
) -> Path:
    # Explicit paths preserve the existing evaluator interface and never fetch.
    if explicit is not None:
        return explicit.expanduser().resolve()
    return ensure_case_support(case_id, destination=destination, offline=offline)
